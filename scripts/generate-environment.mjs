import { config } from 'dotenv';
import { mkdir, writeFile } from 'node:fs/promises';
config({ quiet: true });
const supabaseUrl = process.env.SUPABASE_URL || '';
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY || '';
if (supabaseUrl && !supabaseUrl.includes('YOUR_PROJECT')) {
  const url = new URL(supabaseUrl);
  if (url.protocol !== 'https:' && !(url.protocol === 'http:' && ['localhost','127.0.0.1','10.0.2.2'].includes(url.hostname))) throw new Error('SUPABASE_URL must use HTTPS, except local development.');
}
if (supabaseAnonKey.startsWith('sb_secret_')) throw new Error('Use a publishable/anon key, never a Supabase secret key.');
if (supabaseAnonKey.split('.').length === 3) {
  const payload = JSON.parse(Buffer.from(supabaseAnonKey.split('.')[1], 'base64url').toString());
  if (payload.role !== 'anon') throw new Error('Only an anon key may be embedded in the app.');
}
const settings = { production: process.env.NODE_ENV === 'production', supabaseUrl, supabaseAnonKey, authRedirectUrl: process.env.AUTH_REDIRECT_URL || 'http://localhost:4200/auth/callback' };
await mkdir('src/environments', { recursive: true });
await writeFile('src/environments/environment.ts', '// Generated by npm run config; no server-side secrets.\nexport const environment = '+JSON.stringify(settings, null, 2)+' as const;\n');
console.log(supabaseUrl ? 'Frontend configuration generated.' : 'No Supabase binding yet: the app will show setup instructions.');
